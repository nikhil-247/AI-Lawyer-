def _get_any(form_data: dict, keys: List[str], default: str = "") -> str:
    """
    form_data se multiple possible key names check karke
    first non-empty value return karta hai.
    """
    for k in keys:
        val = form_data.get(k)
        if isinstance(val, str) and val.strip():
            return val.strip()
    return default





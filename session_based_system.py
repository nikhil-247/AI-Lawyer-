# ---------- 4.2 Family Session ----------

def generate_family_story(ctx: PatientContext, answers: Dict) -> str:
    """
    Expected answers keys:
      - language: "hi" / "en"
      - tone: "emotional" / "calm" / "cheerful"
      - family_names: "Anita, Rohan, Dadi"
      - family_vibe_keywords: "supportive, funny, caring"
    """
    lang: Language = answers.get("language", ctx.language)
    name = ctx.name

    raw_family = answers.get("family_names", "")
    raw_vibe = answers.get("family_vibe_keywords", "")

    family_list = [x.strip() for x in raw_family.split(",") if x.strip()]
    vibe_list = [x.strip() for x in raw_vibe.split(",") if x.strip()]

    family_str = ", ".join(family_list) if family_list else ""
    vibe_str = ", ".join(vibe_list) if vibe_list else ""

    if lang == "hi":
        intro = (
            f"{name}, aapki zindagi mein kuch bahut hi khaas log hain. "
        )
        if family_str:
            intro += f"Jaise {family_str}. "
        mid = (
            "In logon ne aapke saath kai halkae, pyaare pal baante hain – "
            "kabhi hansna, kabhi baith kar baatein karna, kabhi sirf ek dusre ke paas shaant baithna. "
        )
        if vibe_str:
            vibe_line = f"Yeh sab log milkar aapke liye ek {vibe_str} sa mehsoos banate rahe hain. "
        else:
            vibe_line = "Inke hone se aapko aksar apnapan, sahara aur narmi ka ehsaas hota hai. "

        scene = (
            "Sochiye, aap sab ek saath baith kar chai pee rahe hain, purani baatein yaad aa rahi hain, "
            "aur kamre mein halki si hasi ghoonj rahi hai. "
            "Unki nazron mein aaj bhi aapki ahmiyat kam nahi hui hai. "
        )

        closing = (
            "Chahe kabhi yaadein halki pad jaati hon, lekin in logon ka pyaar "
            "aapke ird gird ek narm si chaadar ki tarah bana rehta hai. "
            "Aap kabhi akela nahi hain, aur na hi bhool diye gaye hain. "
        )

        text = intro + mid + vibe_line + scene + closing
    else:
        intro = (
            f"{name}, there are some very special people in your life. "
        )
        if family_str:
            intro += f"People like {family_str}. "
        mid = (
            "They have shared many gentle moments with you – "
            "laughing together, talking quietly, or simply sitting nearby in silence. "
        )
        if vibe_str:
            vibe_line = f"Together, they have created a {vibe_str} feeling around you. "
        else:
            vibe_line = (
                "With them around, there is often a feeling of warmth, care and belonging. "
            )

        scene = (
            "You may imagine everyone sitting together, perhaps sharing tea, "
            "remembering old stories, and smiling softly. "
            "In their eyes, your presence is still deeply important. "
        )

        closing = (
            "Even if some details fade from memory, the care they hold for you stays. "
            "You are not alone, and you have not been forgotten. "
        )

        text = intro + mid + vibe_line + scene + closing

    return ensure_min_words(text, lang, min_words=140)



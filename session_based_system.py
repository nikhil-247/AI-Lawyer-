def generate_core_memory_story(ctx: PatientContext, answers: Dict) -> str:
    """
    Expected answers keys:
      - language: "hi" / "en"
      - memory_person: str
      - relation: str
      - category: str (school / travel / festival / birthday / home / other)
      - event_title: str (one line)
      - moment_detail: str (2–4 lines)
      - year_place: str (e.g. "2015, Manali")
    """
    lang: Language = answers.get("language", ctx.language)
    name = ctx.name

    person = answers.get("memory_person", "").strip()
    relation = answers.get("relation", "").strip()
    category = answers.get("category", "other").strip().lower()
    title = answers.get("event_title", "").strip()
    detail = answers.get("moment_detail", "").strip()
    year_place = answers.get("year_place", "").strip()

    if lang == "hi":
        intro = (
            f"Chaliye ek pyaari si yaad ke paas dheere se wapas chalte hain, {name}. "
        )
        if year_place:
            intro += f"Yeh yaad {year_place} ke aas paas ka pal ho sakta hai. "
        if person and relation:
            intro += f"Isme aapke {relation} {person} bhi saath the. "

        title_line = ""
        if title:
            title_line = f"Is pal ko hum chhota sa naam de sakte hain – \"{title}\". "

        cat_line = CATEGORY_ENRICH_HI.get(
            category,
            "Is yaad mein ek narmi, garmahat aur apnapan basa hua hai, jo dil ko shaant kar sakta hai. "
        )

        detail_line = (
            f"{detail} "
            if detail
            else "Us waqt ka mahaul halka, apnapan bhara aur aapke liye bohot khas raha hoga. "
        )

        sensory = (
            "Aap soch sakte hain ki uss din aas paas ka mahaul kaisa tha – "
            "hawa ka ehsaas, aas paas ki awaazein, logon ke chehre, halki si khushboo. "
            "Jaise jaise aap dheere se sochte hain, yeh drishya mann ki screen par dobara ubhar sakta hai. "
        )

        closing = (
            "Yeh yaad abhi bhi aapke andar surakshit hai. "
            "Jab bhi aap chahein, ek gehri saans lekar iss pal ko phir se mehsoos kar sakte hain, "
            "bina kisi jaldi aur bina kisi dabav ke. "
        )

        text = intro + title_line + cat_line + detail_line + sensory + closing
    else:
        intro = (
            f"Let us gently return to a warm memory together, {name}. "
        )
        if year_place:
            intro += f"It may be from around {year_place}. "
        if person and relation:
            intro += f"It includes your {relation}, {person}. "

        title_line = ""
        if title:
            title_line = f"We might give this moment a small name – \"{title}\". "

        cat_line = CATEGORY_ENRICH_EN.get(
            category,
            "This memory seems to hold softness, warmth and a quiet sense of connection. "
        )

        detail_line = (
            f"{detail} "
            if detail
            else "The atmosphere was likely gentle and meaningful, with a feeling that this time together truly mattered. "
        )

        sensory = (
            "You may imagine the sounds around you, the light in the room or outside, "
            "the feel of the air on your skin, and any familiar fragrance in that scene. "
            "As you think slowly, the picture can become clearer in your mind again. "
        )

        closing = (
            "This memory still lives safely within you. "
            "Whenever you wish, you can take a deep, calm breath and visit it again, "
            "without any pressure and only as much as feels comfortable. "
        )

        text = intro + title_line + cat_line + detail_line + sensory + closing

    return ensure_min_words(text, lang, min_words=180)



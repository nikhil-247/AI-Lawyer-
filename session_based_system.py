SAFE_ENRICHMENT_HI = [
    "Aap dheere dheere apni saanso ka ehsaas kar sakte hain.",
    "Yeh baatein sirf aap tak halka sa sukoon pahunchane ke liye hain.",
    "Aap jitna chaahein, utna hi iss pal ko mehsoos kar sakte hain.",
    "Koi jaldi nahi hai, sab kuch dheere aur araam se ho sakta hai.",
    "Aap chahein to aankhen band karke ek gehri saans le sakte hain."
]

SAFE_ENRICHMENT_EN = [
    "You may gently stay with your breath for a moment.",
    "These words are only here to bring you a quiet sense of ease.",
    "You can feel this moment only as much as you are comfortable.",
    "There is no rush, everything can move slowly and softly.",
    "You may close your eyes and take a deep, gentle breath."
]

def ensure_min_words(text: str, lang: Language, min_words: int) -> str:
    """
    Agar story chhoti ho to safe therapeutic lines add karke
    desired length tak le jaata hai.
    """
    words = text.split()
    while len(words) < min_words:
        if lang == "hi":
            words.extend(random.choice(SAFE_ENRICHMENT_HI).split())
        else:
            words.extend(random.choice(SAFE_ENRICHMENT_EN).split())
    return " ".join(words)


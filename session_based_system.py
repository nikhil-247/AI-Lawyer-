# ---------- 4.6 Custom Session ----------

def generate_custom_story(ctx: PatientContext, answers: Dict) -> str:
    """
    Expected answers keys:
      - language: "hi" / "en"
      - tone: "calm" / "cheerful" / "informative" / "emotional"
      - title: str
      - main_points: str (CSV of 3–6 short points)
      - avoid_topics: str (CSV) [not used directly]
      - length_pref: "short" / "medium" / "long"
    """
    lang: Language = answers.get("language", ctx.language)
    name = ctx.name

    title = answers.get("title", "").strip()
    raw_points = answers.get("main_points", "")
    length_pref = answers.get("length_pref", "medium")

    points = [p.strip() for p in raw_points.split(",") if p.strip()]

    if length_pref == "short":
        min_words = 90
    elif length_pref == "long":
        min_words = 180
    else:
        min_words = 130

    if lang == "hi":
        intro = f"{name}, ab hum ek chhoti si baat aap tak pohchana chahte hain. "
        if title:
            intro += f"Is baat ka ek saral sa vishay hai – \"{title}\". "

        body_parts = []
        for p in points:
            body_parts.append(
                f"Ek zaroori baat yeh hai ki {p}. "
                "Isse aap tak sirf halka sa sandesh, samajh aur sukoon pahunchana chahte hain. "
            )

        if not body_parts:
            body_parts.append(
                "Yeh kuch aisi baatein hain jo sirf aapko yaad dilati hain "
                "ki log aapke baare mein soch rahe hain aur aapka khayal rakh rahe hain. "
            )

        body = " ".join(body_parts)

        closing = (
            "In sab baaton ka uddeshya sirf itna hai ki aapko thoda sa saaf, "
            "aasaan aur narm sandesh mil sake. "
            "Aap jitna chaahein utna hi iss message ko andar aane de sakte hain. "
        )

        text = intro + body + closing
    else:
        intro = f"{name}, we would like to share a small message with you. "
        if title:
            intro += f"The simple theme of this message is \"{title}\". "

        body_parts = []
        for p in points:
            body_parts.append(
                f"One important point is that {p}. "
                "This is shared only to bring you a little more clarity and ease. "
            )

        if not body_parts:
            body_parts.append(
                "These are gentle reminders that people are thinking of you "
                "and are trying to care for you in a clear and simple way. "
            )

        body = " ".join(body_parts)

        closing = (
            "The purpose of these words is only to offer a calm, understandable message. "
            "You may take in as much or as little as feels right for you. "
        )

        text = intro + body + closing

    return ensure_min_words(text, lang, min_words=min_words)



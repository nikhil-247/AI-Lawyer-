# ============================================
# STEP 5: Main dispatcher – session_type → story
# ============================================

def generate_session_story(
    session_type: SessionType,
    patient_context: PatientContext,
    answers: Dict
) -> str:
    """
    Ye function frontend ke liye main entry point jaisa hoga.
    FastAPI se bhi isi ko call kara sakte ho.
    """
    if session_type == "reassurance":
        return generate_reassurance_story(patient_context, answers)
    elif session_type == "family":
        return generate_family_story(patient_context, answers)
    elif session_type == "core_memory":
        return generate_core_memory_story(patient_context, answers)
    elif session_type == "morning_routine":
        return generate_morning_routine_story(patient_context, answers)
    elif session_type == "night_routine":
        return generate_night_routine_story(patient_context, answers)
    elif session_type == "custom":
        return generate_custom_story(patient_context, answers)
    elif session_type == "grounding":
        return generate_grounding_story(patient_context, answers)
    else:
        raise ValueError(f"Unsupported session_type: {session_type}")



client = ElevenLabs(api_key=ELEVEN_API_KEY)

# Apne account ke voices ke IDs dalao (example IDs, replace with yours)
VOICE_MAP = {
    ("hi", "male"):   "zgqefOY5FPQ3bB7OZTVR", #Niraj
    ("hi", "female"): "1qEiC6qsybMkmnNdVMbK", #Monika
    ("en", "male"):   "JBFqnCBsd6RMkjVDRZzb", #George
    ("en", "female"): "pFZP5JQG7iQjIQuC4Bku"  #Lily
}

def generate_voice_bytes(story_text: str, language: Language, gender: VoiceGender) -> bytes:
    key = (language, gender)
    voice_id = VOICE_MAP.get(key)

    if voice_id is None:
        # fallback: koi bhi pehla voice
        voices = client.voices.get_all()
        if voices.voices:
            voice_id = voices.voices[0].voice_id
        else:
            raise RuntimeError("No voices available in ElevenLabs account.")

    stream = client.text_to_speech.convert(
        voice_id=voice_id,
        model_id="eleven_multilingual_v2",
        text=story_text,
        output_format="mp3_44100_128",
    )
    audio_bytes = b"".join(stream)
    return audio_bytes


def play_and_save_voice(
    story_text: str,
    language: Language,
    gender: VoiceGender,
    filename: str = "therapy_session.mp3"
):
    try:
        audio_bytes = generate_voice_bytes(story_text, language, gender)
        # Colab / Jupyter pe play button
        display(Audio(audio_bytes, autoplay=False))
        Path(filename).write_bytes(audio_bytes)
        print("🎧 Audio saved as:", filename)
        return filename
    except Exception as e:
        print("⚠ ElevenLabs error:", e)
        print("Story text generated successfully, but audio not created.")
        return None


